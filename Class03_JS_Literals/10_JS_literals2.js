
// 1. Numeric literals: These represent numbers, such as integers and floating-point numbers.
let integerLiteral = 42; // Integer literal
let floatLiteral = 3.14; // Floating-point literal  

// 2. String literals: These represent sequences of characters enclosed in single or double quotes.
let singleQuoteString = 'Hello, World!';    

let doubleQuoteString = "Hello, JavaScript!";

// 3. Boolean literals: These represent the two boolean values, true and false.
let isTrue = true; // Boolean literal
let isFalse = false; // Boolean literal


// 4. Array literals: These represent arrays, which are ordered collections of values enclosed in square brackets.
let arrayLiteral = [1, 2, 3, 4, 5]; // Array literal    

// 5. Object literals: These represent objects, which are collections of key-value pairs enclosed in curly braces.
let objectLiteral = { name: "John", age: 30, city: "New York" }; // Object literal  

// 6. Null literal: This represents the absence of any value.
let nullLiteral = null; // Null literal

// 7. Undefined literal: This represents a variable that has been declared but has not been assigned a value.
let undefinedLiteral; // Undefined literal

// 8. Regular expression literals: These represent regular expressions, which are patterns used for matching text.

let regexLiteral = /ab+c/; // Regular expression literal

// 9. Template literals: These represent strings that can contain embedded expressions and multi-line text, enclosed in backticks.
let name = "Alice";
let templateLiteral = `Hello, ${name}!`; // Template literal with embedded expression   

// 10. BigInt literals: These represent integers that are too large to be represented by the Number type, and are denoted by appending an "n" to the end of the integer.
let bigIntLiteral = 1234567890123456789012345678901234567890n; // BigInt literal

// 11. Symbol literals: These represent unique and immutable values, created using the Symbol() function.
let symbolLiteral = Symbol("mySymbol"); // Symbol literal

// 12. Function literals: These represent functions, which are blocks of code that can be executed when called.
let functionLiteral = function() { return "Hello, World!"; };

// 13. Class literals: These represent classes, which are templates for creating objects with shared properties and methods.
class MyClass { constructor(name) { this.name = name; } } // Class literal  
